    private void btnPagoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPagoActionPerformed
        try {
        int row = jTable1.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Selecione um cliente na tabela.");
            return;
        }

        int clienteId = Integer.parseInt(jTable1.getValueAt(row, 0).toString());

        AluguelDAO.marcarPagoEDevolver(clienteId);

        JOptionPane.showMessageDialog(this, "Pago confirmado e livro devolvido ao estoque!");
        // recarrega tabela
        carregarTabelaClientes(NomeConsulta.getText().trim());

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Erro: " + e.getMessage());
        e.printStackTrace();
    }
    }//GEN-LAST:event_btnPagoActionPerformed

