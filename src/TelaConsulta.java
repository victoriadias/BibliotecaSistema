    private void carregarTabelaClientes(String termo) {
    try {
        DefaultTableModel m = (DefaultTableModel) jTable1.getModel();
        m.setRowCount(0);

        ResultSet rs = ConsultaDAO.buscarClientes(termo);
        while (rs.next()) {
            m.addRow(new Object[] {
                rs.getInt("id"),
                rs.getString("nome"),
                rs.getString("email"),
                rs.getString("telefone"),
                rs.getString("livro"),
                rs.getInt("quantidade"),
                rs.getDouble("valor"),
                rs.getString("status_pagamento")
            });
        }
        rs.getStatement().getConnection().close();
    } catch (Exception e) {
        e.printStackTrace();
    }
}
