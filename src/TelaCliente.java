    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try {
        String nome = Nome1.getText().trim();
        String email = Email1.getText().trim();
        String tel = Telefone1.getText().trim();
        String livroTitulo = Livro1.getText().trim();

        int qtd = Integer.parseInt(Quantidade1.getText().trim());
        double valor = Double.parseDouble(Valor1.getText().trim().replace(",", "."));

        AluguelDAO.cadastrarClienteComAluguel(nome, email, tel, livroTitulo, qtd, valor);

        JOptionPane.showMessageDialog(this, "Cliente cadastrado e livro alugado! Status: PENDENTE");

        Nome1.setText("");
        Email1.setText("");
        Telefone1.setText("");
        Livro1.setText("");
        Quantidade1.setText("");
        Valor1.setText("");

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Erro: " + e.getMessage());
        e.printStackTrace();
    }
    }//GEN-LAST:event_jButton1ActionPerformed

